"""Report agent: turns collected evidence into an RCA with recommended corrective actions."""

from __future__ import annotations

import logging

from tsagent.graph.context import evidence_digest, incident_header
from tsagent.graph.deps import GraphDeps
from tsagent.graph.schemas import RCA
from tsagent.graph.state import IncidentState
from tsagent.llm import LLMError
from tsagent.models import IncidentStatus, Report
from tsagent.reporting import render_report
from tsagent.reporting.notifier import notify_report

logger = logging.getLogger(__name__)

# Ceiling on reported confidence when nothing could be verified against the cluster.
UNVERIFIED_CONFIDENCE_CAP = 0.2

SYSTEM = (
    "You are an SRE writing the root-cause section of an incident report for a RHOSP platform "
    "team. Ground every claim in the evidence provided; if the evidence is thin, say so and "
    "lower the confidence rather than guessing. Recommendations must be concrete actions an "
    "operator can take.\n"
    "The root cause is why the ALARM fired. If a tool failed — Prometheus unreachable, a TLS or "
    "auth error, a model timeout — that is a failure of this investigation, not the cause of the "
    "incident. Put it in caveats, keep the root cause as what is actually unknown, and set a low "
    "confidence. Never report a monitoring failure as the root cause of an infrastructure alarm.\n"
    "\n"
    "Evidence interpretation:\n"
    "- /proc/meminfo HugePages_Total=N and HugePages_Free=0 means the hugepage pool is FULLY "
    "  allocated (the hugepage alarm firing is expected/accurate). If Free is falling over time "
    "  guests are claiming pages; a flat low count on a populated compute node is normal.\n"
    "- hugetlb near MemTotal means hugepages dominate RAM by design (hugepagesz=1G on kernel "
    "  cmdline), not a leak.\n"
    "- podman ps: 'Up' = running, 'Exited' = crashed, 'Restarting' = crash-loop.\n"
    "- pcs resource status: 'Started' on another controller means the resource migrated, not lost."
)


async def report_node(state: IncidentState, deps: GraphDeps) -> dict:
    promql_evidence = state.get("promql_evidence") or []
    node_evidence = state.get("node_evidence") or []
    plan = state.get("plan") or {}
    caveats = list(state.get("caveats") or [])

    messages = [
        {"role": "system", "content": SYSTEM},
        {
            "role": "user",
            "content": (
                f"{incident_header(state)}\n\n"
                f"Hypotheses: {'; '.join(plan.get('hypotheses') or []) or 'none'}\n\n"
                # Keep the evidence bounded: the 8B model has a 4096-token context
                # window, and a podman ps / pcs status dump across retries easily
                # exceeds it, failing the whole report step. max_chars here is the
                # hard TOTAL budget for each digest; result_chars caps each result.
                f"Metric evidence:\n{evidence_digest(promql_evidence, limit=6, max_chars=1500, result_chars=250)}\n\n"
                f"Node evidence:\n{evidence_digest(node_evidence, limit=6, max_chars=1500, result_chars=250)}\n\n"
                'Reply with JSON only: {"root_cause": "...", "confidence": 0.0, '
                '"recommendations": ["..."], "caveats": ["..."], "timeline": ["..."]}'
            ),
        },
    ]

    try:
        rca = await deps.gateway.complete_json("report", messages, RCA, max_tokens=900)
    except LLMError as exc:
        logger.error("RCA generation failed: %s", exc)
        rca = RCA(
            root_cause="Undetermined — the reporting model was unavailable.",
            confidence=0.0,
            recommendations=[
                "Review the evidence below manually.",
                "Check that the configured LLM endpoint is reachable from the agent pod.",
            ],
        )
        caveats.append(f"The RCA section was not generated by a model ({exc}).")

    caveats.extend(c for c in rca.caveats if c not in caveats)

    # A model with no evidence will still answer confidently — in lab testing it reported a TLS
    # failure as the root cause of a hugepage alarm at 100% confidence. Confidence is a claim
    # about evidence, so when none was collected the number has to reflect that regardless of
    # what the model asserted.
    verified = [e for e in promql_evidence + node_evidence if e.get("ok")]
    if not verified and rca.confidence > UNVERIFIED_CONFIDENCE_CAP:
        logger.warning(
            "capping reported confidence %.2f -> %.2f: no evidence was successfully collected",
            rca.confidence, UNVERIFIED_CONFIDENCE_CAP,
        )
        rca.confidence = UNVERIFIED_CONFIDENCE_CAP
        caveats.insert(
            0,
            "No evidence was successfully collected, so the root cause below is inferred from "
            "the alarm text alone and has not been verified against the cluster.",
        )

    incident = dict(state.get("incident") or {})
    markdown = render_report(
        incident=incident,
        alarms=state.get("alarms") or [],
        plan=plan,
        promql_evidence=promql_evidence,
        node_evidence=node_evidence,
        rca=rca.model_dump(),
        caveats=caveats,
        decision_reason=state.get("decision_reason", ""),
    )

    report = Report(
        incident_id=state["incident_id"],
        root_cause=rca.root_cause,
        confidence=rca.confidence,
        recommendations=rca.recommendations,
        caveats=caveats,
        markdown=markdown,
        data={
            "plan": plan,
            "promql_evidence": promql_evidence,
            "node_evidence": node_evidence,
            "reflections": state.get("reflections") or [],
            "decision": state.get("decision", ""),
            "decision_reason": state.get("decision_reason", ""),
        },
    )

    if deps.repo:
        await deps.repo.save_report(report)
        stored = await deps.repo.get_incident(state["incident_id"])
        if stored:
            stored.status = IncidentStatus.REPORTED
            stored.summary = stored.summary or incident.get("summary", "")
            await deps.repo.save_incident(stored)

    await notify_report(deps.app_config.report.notify_webhook, report)

    logger.info(
        "report ready: incident=%s confidence=%.2f recommendations=%d",
        state["incident_id"], rca.confidence, len(rca.recommendations),
    )
    return {"report": report.model_dump(mode="json"), "caveats": []}
